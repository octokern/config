import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import type { FieldDescription } from '../../schema/introspection.js';
import { color } from '../format.js';
import { getOptionString, hasOption } from '../args.js';
import type { CommandContext } from './shared.js';
import { getOutPath, loadDefinitions } from './shared.js';

function stringifyDefault(value: unknown): string {
  if (typeof value === 'string') return value;
  if (value === undefined) return '';
  return JSON.stringify(value);
}

function sampleValue(field: FieldDescription): string {
  if (field.secret) return field.placeholder ?? '<set-me>';
  if (field.example !== undefined) return field.example;
  if (field.placeholder !== undefined) return field.placeholder;
  if (field.defaultValue !== undefined) return stringifyDefault(field.defaultValue);
  if (field.enumValues?.length) return String(field.enumValues[0]);
  if (field.type === 'boolean') return 'false';
  if (field.type === 'number' || field.type === 'port') return field.type === 'port' ? '3000' : '0';
  if (field.type === 'array' || field.type === 'list') return 'item1,item2';
  if (field.type === 'duration') return '30s';
  return '<value>';
}

export function renderEnvExample(fields: readonly FieldDescription[]): string {
  const lines = [
    '# Generated by @octokern/config',
    '# Copy this file to .env and fill in values for your environment.',
    '',
  ];
  let currentGroup: string | undefined;
  for (const field of fields) {
    if (!field.includeInExample) continue;
    const group = field.group;
    if (group && group !== currentGroup) {
      if (lines[lines.length - 1] !== '') lines.push('');
      lines.push(`# ${group}`);
      currentGroup = group;
    }
    if (field.name !== field.key) lines.push(`# ${field.name}`);
    if (field.description) lines.push(...field.description.split(/\r?\n/).map((line) => `# ${line}`));
    if (field.comment) lines.push(...field.comment.split(/\r?\n/).map((line) => `# ${line}`));
    if (field.deprecated) lines.push(`# DEPRECATED${typeof field.deprecated === 'string' ? `: ${field.deprecated}` : ''}`);
    if (field.secret) lines.push('# SECRET');
    lines.push(`${field.key}=${sampleValue(field)}`);
    lines.push('');
  }
  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}

export async function exampleCommand(context: CommandContext): Promise<void> {
  const definitions = await loadDefinitions(context);
  const fields = definitions.flatMap((definition) => definition.describeFields());
  const output = renderEnvExample(fields);
  if (hasOption(context.args.options, 'stdout')) {
    console.log(output);
    return;
  }
  const path = getOutPath(context.args, '.env.example');
  if (hasOption(context.args.options, 'check')) {
    const existing = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : undefined;
    if (existing === output) {
      console.log(color.green(`${path} is up to date`));
      process.exitCode = 0;
    } else {
      console.error(color.red(`${path} is out of date. Run @octokern/config example.`));
      process.exitCode = 1;
    }
    return;
  }
  writeFileSync(path, output, 'utf8');
  console.log(color.green(`Generated ${path}`));
  const customOutput = getOptionString(context.args.options, 'out');
  if (customOutput) console.log(color.gray(`Output: ${customOutput}`));
}
