import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, writeFileSync } from 'node:fs';
import type { FieldDescription } from '../../schema/introspection.js';
import { color } from '../format.js';
import type { CommandContext } from './shared.js';
import { getOutPath, loadDefinitions } from './shared.js';
import { hasOption } from '../args.js';

function generatedSecret(minLength: number | undefined): string {
  const desiredLength = Math.max(16, minLength ?? 32);
  let result = '';
  while (result.length < desiredLength) {
    result += randomBytes(Math.max(16, Math.ceil((desiredLength - result.length) * 0.8))).toString('base64url');
  }
  return result.slice(0, desiredLength);
}

function initialValue(field: FieldDescription): string {
  if (field.secret) return generatedSecret(field.minLength);
  if (field.defaultValue !== undefined) return typeof field.defaultValue === 'string' ? field.defaultValue : JSON.stringify(field.defaultValue);
  if (field.example !== undefined) return field.example;
  if (field.placeholder !== undefined) return field.placeholder;
  if (field.enumValues?.length) return String(field.enumValues[0]);
  return '';
}

export function renderInitialEnv(fields: readonly FieldDescription[]): string {
  const lines = ['# Generated by @octokern/config', '# Review generated secrets and environment-specific values before deployment.', ''];
  let group: string | undefined;
  for (const field of fields) {
    if (!field.includeInExample) continue;
    if (field.group && field.group !== group) {
      if (lines[lines.length - 1] !== '') lines.push('');
      lines.push(`# ${field.group}`);
      group = field.group;
    }
    if (field.name !== field.key) lines.push(`# ${field.name}`);
    if (field.description) lines.push(`# ${field.description.replace(/\r?\n/g, '\n# ')}`);
    if (field.comment) lines.push(`# ${field.comment.replace(/\r?\n/g, '\n# ')}`);
    if (field.deprecated) lines.push(`# DEPRECATED${typeof field.deprecated === 'string' ? `: ${field.deprecated}` : ''}`);
    if (field.secret) lines.push('# SECRET — generated locally; keep this file private.');
    lines.push(`${field.key}=${initialValue(field)}`);
    lines.push('');
  }
  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}

export async function initCommand(context: CommandContext): Promise<void> {
  const definitions = await loadDefinitions(context);
  const fields = definitions.flatMap((definition) => definition.describeFields());
  const outputPath = getOutPath(context.args, '.env');
  if (existsSync(outputPath) && !hasOption(context.args.options, 'force')) {
    throw new Error(`${outputPath} already exists. Pass --force to overwrite it.`);
  }
  writeFileSync(outputPath, renderInitialEnv(fields), { encoding: 'utf8', mode: 0o600 });
  try { chmodSync(outputPath, 0o600); }
  catch (error) { if (process.platform !== 'win32') throw error; }
  console.log(color.green(`Created ${outputPath}`));
}
